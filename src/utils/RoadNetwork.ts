export const ROAD_NETWORK_GEOJSON: FeatureCollection<LineString> = {
  type: "FeatureCollection",
  features: ROAD_ROUTES.map((route) => ({
    type: "Feature",
    properties: {
      id: route.id,
      name: route.name,
      direction: route.direction,
      isMainCorridor: route.isMainCorridor,
    },
    geometry: {
      type: "LineString",
      coordinates: route.coordinates,
    },
  })),
};

export function getRandomRoadRoute(): Feature<LineString> {
  const idx = Math.floor(Math.random() * ROAD_NETWORK_GEOJSON.features.length);
  return ROAD_NETWORK_GEOJSON.features[idx];
}

export function getRoadRouteById(id: string): Feature<LineString> | undefined {
  return ROAD_NETWORK_GEOJSON.features.find((f) => f.properties?.id === id);
}
